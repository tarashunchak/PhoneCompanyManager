
CREATE TABLE Reports (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    cust_id INTEGER REFERENCES Customers(id) NOT NULL,
    description VARCHAR(255) NOT NULL,
    status TEXT NOT NULL DEFAULT 'In Progress',
    date TIMESTAMP NOT NULL
);

CREATE TABLE Payments (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    cust_id INTEGER REFERENCES Customers(id) NOT NULL,
    amount REAL NOT NULL,
    payment_type TEXT NOT NULL,
    payment_date TIMESTAMP NOT NULL
);

CREATE TABLE CustomersUsers (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    cust_id INTEGER REFERENCES Customers(id) UNIQUE NOT NULL,
    phone TEXT UNIQUE,
    pass_hash TEXT
);

CREATE TABLE Employees (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    department_id INTEGER NOT NULL REFERENCES Departments(id),
    position_id INTEGER NOT NULL REFERENCES Positions(id),
    hire_date DATE NOT NULL,
    salary REAL NOT NULL,
    phone TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE NOT NULL
);

CREATE TABLE Departments (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    department_name TEXT UNIQUE NOT NULL
);

CREATE TABLE Positions (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    position_name VARCHAR(255) UNIQUE NOT NULL
);

CREATE TABLE Users (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    empl_id INTEGER REFERENCES Employees(id) UNIQUE,
    username VARCHAR(255) UNIQUE,
    pass_hash TEXT
);

CREATE TABLE Tariffs (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    tariff_name VARCHAR(255) UNIQUE NOT NULL,
    daily_price REAL,
    monthly_price REAL NOT NULL,
    call_minutes REAL NOT NULL,
    internet_GB REAL,
    messages INTEGER
);

CREATE TABLE Requests (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    cust_id INTEGER NOT NULL REFERENCES Customers(id),
    request_type TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'In Progress',
    date TIMESTAMP NOT NULL
);

CREATE TABLE Customers (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    phone VARCHAR(255) NOT NULL UNIQUE,
    date_of_B VARCHAR(255) NOT NULL,
    date TIMESTAMP NOT NULL,
    tariff_id INTEGER REFERENCES Tariffs(id)
);

CREATE TABLE Usage (
    id SERIAL PRIMARY KEY UNIQUE NOT NULL,
    cust_id INTEGER REFERENCES Customers(id) NOT NULL,
    sms_send INTEGER NOT NULL,
    date TIMESTAMP NOT NULL,
    used_minutes REAL NOT NULL
);

CREATE TABLE IF NOT EXISTS "Messages" (
    id SERIAL PRIMARY KEY NOT NULL,
    message_text TEXT NOT NULL,
    date_time TIMESTAMP NOT NULL,
    origin INTEGER NOT NULL,
    destination TEXT NOT NULL
);

